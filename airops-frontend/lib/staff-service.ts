import api from "@/lib/axios-config"

export interface StaffRole {
  id: string;
  displayName: string;
}

export interface Department {
  id: string;
  displayName: string;
}

export interface StaffStatus {
  id: string;
  displayName: string;
}

export interface StaffMember {
  id: number;
  employeeId: string;
  firstName: string;
  lastName: string;
  email: string;
  staffRole: StaffRole;
  department: Department;
  status: StaffStatus;
  hireDate: string;
  roleDisplayName: string;
  departmentDisplayName: string;
  statusDisplayName: string;
}

export interface CreateStaffRequest {
  employeeId?: string; // Optional - will be auto-generated by backend
  firstName: string;
  lastName: string;
  email: string;
  staffRole: string;
  department: string;
  hireDate: string;
  status?: string;
}

export interface UpdateStaffRequest extends CreateStaffRequest {
  id: number;
}

export interface StaffListResponse {
  content: StaffMember[];
  totalElements: number;
  totalPages: number;
  size: number;
  number: number;
}

class StaffService {
  // Get all staff with pagination
  async getAllStaff(page: number = 0, size: number = 20): Promise<StaffListResponse> {
    const response = await api.get(`/staff?page=${page}&size=${size}`)
    return response.data
  }

  // Get staff by ID
  async getStaffById(id: number): Promise<StaffMember> {
    const response = await api.get(`/staff/${id}`)
    return response.data
  }

  // Create new staff member
  async createStaff(staffData: CreateStaffRequest): Promise<StaffMember> {
    const response = await api.post('/staff', staffData)
    return response.data
  }

  // Update staff member
  async updateStaff(id: number, staffData: CreateStaffRequest): Promise<StaffMember> {
    const response = await api.put(`/staff/${id}`, staffData)
    return response.data
  }

  // Delete staff member
  async deleteStaff(id: number): Promise<void> {
    await api.delete(`/staff/${id}`)
  }

  // Get staff by role
  async getStaffByRole(role: string): Promise<StaffMember[]> {
    const response = await api.get(`/staff/role/${role}`)
    return response.data
  }

  // Get staff by status
  async getStaffByStatus(status: string): Promise<StaffMember[]> {
    const response = await api.get(`/staff/status/${status}`)
    return response.data
  }

  // Get staff by hire date range
  async getStaffByHireDateRange(startDate: string, endDate: string): Promise<StaffMember[]> {
    const response = await api.get(`/staff/hire-date?startDate=${startDate}&endDate=${endDate}`)
    return response.data
  }

  // Get all available roles
  async getAllRoles(): Promise<StaffRole[]> {
    const response = await api.get('/staff/roles')
    const roles = response.data
    
    // Transform the enum values to match our interface
    return roles.map((role: string) => ({
      id: role,
      displayName: this.getRoleDisplayName(role)
    }))
  }

  // Get all available statuses
  async getAllStatuses(): Promise<StaffStatus[]> {
    const response = await api.get('/staff/statuses')
    const statuses = response.data
    
    // Transform the enum values to match our interface
    return statuses.map((status: string) => ({
      id: status,
      displayName: this.getStatusDisplayName(status)
    }))
  }

  // Get all available departments
  async getAllDepartments(): Promise<Department[]> {
    const response = await api.get('/staff/departments')
    const departments = response.data
    
    // Transform the enum values to match our interface
    return departments.map((dept: string) => ({
      id: dept,
      displayName: this.getDepartmentDisplayName(dept)
    }))
  }

  // Helper methods to get display names
  private getRoleDisplayName(role: string): string {
    const roleMap: Record<string, string> = {
      'PILOT': 'Pilot',
      'CO_PILOT': 'Co-Pilot',
      'FLIGHT_ATTENDANT': 'Flight Attendant',
      'GROUND_CREW': 'Ground Crew',
      'MAINTENANCE_TECHNICIAN': 'Maintenance Technician',
      'SUPERVISOR': 'Supervisor',
      'MANAGER': 'Manager',
      'ADMINISTRATIVE': 'Administrative'
    };
    return roleMap[role] || role;
  }

  private getStatusDisplayName(status: string): string {
    const statusMap: Record<string, string> = {
      'ACTIVE': 'Active',
      'INACTIVE': 'Inactive',
      'ON_LEAVE': 'On Leave',
      'SUSPENDED': 'Suspended',
      'TERMINATED': 'Terminated'
    };
    return statusMap[status] || status;
  }

  private getDepartmentDisplayName(dept: string): string {
    const deptMap: Record<string, string> = {
      'FLIGHT_OPERATIONS': 'Flight Operations',
      'MAINTENANCE': 'Maintenance',
      'CUSTOMER_SERVICE': 'Customer Service',
      'ADMINISTRATION': 'Administration',
      'HUMAN_RESOURCES': 'Human Resources',
      'IT': 'Information Technology'
    };
    return deptMap[dept] || dept;
  }
}

export const staffService = new StaffService();
export default staffService;
